function gtgPrescriptions(fields: {
  repsLow?: number;
  repsHigh?: number;
  secLow?: number;
  secHigh?: number;
  rpeLow?: number;
  rpeHigh?: number;
  note?: string;
}): Prescription[] {
  return GTG_ROUNDS.map((sets, i) => ({ weeks: [i + 1], sets, ...fields }));
}


